% Tetrahedron geometry data for MATLAB

% Define tetrahedron vertex positions
v0 = [0.0, -0.5, 0.0];   % Bottom left
v1 = [0.0, 0.5, 0.0];    % Bottom right
v2 = [0.0, 0.0, 0.5];    % Top
v3 = [-0.5, 0.0, 0.0];   % Back

% Tetrahedron vertices - 4 triangular faces (12 vertices total)
vertices = [
    % Face 1: bottom (v0, v1, v3)
    v0(1), v0(2), v0(3),...
    v1(1), v1(2), v1(3),...
    v3(1), v3(2), v3(3),...
    v1(1), v1(2), v1(3),...
    v2(1), v2(2), v2(3),...
    v3(1), v3(2), v3(3),...
    v2(1), v2(2), v2(3),...
    v0(1), v0(2), v0(3),...
    v3(1), v3(2), v3(3),...
    v0(1), v0(2), v0(3),...
    v2(1), v2(2), v2(3),...
    v1(1), v1(2), v1(3)
];

% Triangle IDs for each vertex
triangleIDs = uint32([
    % Face 1 bottom: Red
    1, 1, 1,...
    2, 2, 2,...
    3, 3, 3,...
    4, 4, 4
]);

% Convert to single precision for OpenGL compatibility
vertices = single(vertices);

% Number of vertices and triangles
numVertices = length(vertices);
numTriangles = length(triangleIDs);
